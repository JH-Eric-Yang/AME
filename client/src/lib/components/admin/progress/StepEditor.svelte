<script lang="ts">
  import type { RoutineConfig } from "ame-shared";
  import type { Step } from "ame-shared/progressSequence";
  import { findOwningDesign, describeOwnership } from "ame-shared/blockOwnership";
  import { experiment } from "$lib/stores/experiment";
  import ElementOverride from "./ElementOverride.svelte";

  let { step, routine, routines, content, experimentId, onchangecontent, onchangeroutine }: {
    step: Step; routine: RoutineConfig | undefined; routines: RoutineConfig[]; content: Record<string, unknown>;
    experimentId: string; onchangecontent: (content: Record<string, unknown>) => void; onchangeroutine: (routine: RoutineConfig) => void;
  } = $props();

  const freeMode = $derived((routine?.layout.mode ?? "flow") === "free");
  const owner = $derived(step.generated ? findOwningDesign(step.routine, $experiment.sessionDesigns ?? []) : null);
  let jsonError = $state("");

  function pickRoutine(name: string) {
    const next = routines.find((r) => r.name === name);
    if (!next || next.name === step.routine) return;
    // Compare against `next`'s elements, not the current routine's — the
    // question is what the row would still exercise after the switch, so
    // an override the incoming routine still has an element for survives.
    const keep = new Set(next.elements.map((e) => e.name));
    const dropped = Object.keys(content).filter((k) => !keep.has(k));
    if (dropped.length > 0 && !confirm(`Switching to "${name}" drops overrides for: ${dropped.join(", ")}. Continue?`)) return;
    onchangeroutine(next);
  }

  function applyJson(text: string) {
    try {
      const parsed = JSON.parse(text);
      if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) throw new Error("content must be a JSON object");
      jsonError = "";
      onchangecontent(parsed);
    } catch (e) {
      jsonError = e instanceof Error ? e.message : "invalid JSON";
    }
  }
</script>

<div class="step-editor">
  <header>
    <span class="pos mono">p{step.position}</span>
    <span class="trial mono">t{step.trial}</span>
    <select aria-label="Routine" value={step.routine} disabled={step.generated} onchange={(e) => pickRoutine(e.currentTarget.value)}>
      {#each routines as r (r.name)}<option value={r.name}>{r.name}</option>{/each}
      {#if !routine}<option value={step.routine}>{step.routine} (missing)</option>{/if}
    </select>
  </header>

  {#if step.generated}
    <p class="owned">{owner ? describeOwnership(owner) : "Generated by a Session Design block"} — edit it in the Session tab.</p>
  {:else if !routine}
    <p class="owned">Routine "{step.routine}" is not in this experiment. Pick another routine above.</p>
  {:else}
    <!-- Editors keep local UI state (e.g. TextParamsEditor's "Custom… chosen,
         nothing typed yet" flag). Keying by routine name + element name is
         what scopes that state to one element even though `StepEditor` stays
         mounted across a routine switch at the same position — two routines
         may share an element name, so the name alone is not enough. -->
    {#each routine.elements as element (`${routine.name}:${element.name}`)}
      <ElementOverride {element} {content} {freeMode} {experimentId} onchange={onchangecontent} />
    {/each}
    {#if routine.elements.length === 0}<p class="hint">This routine has no elements.</p>{/if}

    <details class="advanced">
      <summary>Advanced</summary>
      <textarea aria-label="Content JSON" rows="6" value={JSON.stringify(content, null, 2)} onchange={(e) => applyJson(e.currentTarget.value)}></textarea>
      {#if jsonError}<p class="error">{jsonError}</p>{/if}
    </details>
  {/if}
</div>

